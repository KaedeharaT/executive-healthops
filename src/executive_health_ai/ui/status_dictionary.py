def status_label(value, *, context=None):
    raw = str(value or "").strip()
    code = raw.upper()
    if context and code in CONTEXT_STATUS.get(context, {}):
        return CONTEXT_STATUS[context][code]
    if code in STATUS:
        return STATUS[code]
    if raw in ALIASES:
        return ALIASES[raw]
    if raw in STATUS.values():
        return raw
    return "待确认" if raw else "未记录"
