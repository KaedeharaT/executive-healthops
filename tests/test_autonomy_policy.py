def rule(session, level, route='HEALTH_MANAGER'):
    row = RiskRule(name='合成测试规则，非临床阈值', code='SYNTHETIC_'+str(uuid4()), applicable_device_class='ANY',
        canonical_code='steps', risk_level=level, condition_type='SYNTHETIC_TEST_THRESHOLD',
        threshold_config={'metric':'steps', 'operator':'>=', 'value':'8000', 'unit':'count'},
        window_config={}, action_type='SYNTHETIC_TEST_ONLY', source_reference='非临床合成验收依据',
        review_status='APPROVED', reviewed_by='测试规则审核人', recommended_route=route, version='test-1')
    session.add(row); session.flush()
    return row


def change(session, p, level, route='HEALTH_MANAGER', supervisor=None):
    rule(session, level, route)
    obs = Observation(patient_id=p.patient_id, observed_at=utc_now(), metric_code='steps',
        value_numeric=9000, unit='count', source='DEVICE', quality_flag='valid')
    session.add(obs); session.flush()
    event, _ = ingest_health_event(session, member_id=p.patient_id, event_type='MEANINGFUL_CHANGE',
        event_category='MEANINGFUL_CHANGE', source_type='SYSTEM', source_id=str(uuid4()),
        payload_ref={'observation_ids':[str(obs.id)], 'llm_risk':'GREEN', 'confidence':1}, supervisor=supervisor)
    session.flush()
    goal = session.get(AgentGoal, event.goal_id)
    return event, goal


def human(session, p):
    return [i for i in OperationalWorklistService().list_items(session, utc_now()) if i.member_id == p.patient_id]


