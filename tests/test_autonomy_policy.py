def test_device_100_raw_zero_wake_one_change_one_evaluation(db,monkeypatch):
    s,p=db;rule(s,'YELLOW');now=utc_now()
    from executive_health_ai.services.risk_triage import RiskEvaluationService
    original=RiskEvaluationService.evaluate_observation
    evaluations=[]
    def counted(self,session,observation_id):
        evaluations.append(observation_id)
        return original(self,session,observation_id)
    monkeypatch.setattr(RiskEvaluationService,'evaluate_observation',counted)
    for n in range(100):
        ingest_health_event(s,member_id=p.patient_id,event_type='DEVICE_RAW_MEASUREMENT',event_category='NEW_INFORMATION',
            source_type='DEVICE',source_id=str(n),payload_ref={'measurement':{'metric':'steps','value':9000,'unit':'count','observed_at':now.isoformat()}})
    agent=s.scalar(select(MemberAgent).where(MemberAgent.member_id==p.patient_id))
    assert agent.wake_count==0 and s.scalar(select(func.count(Observation.id)))==100
    assert evaluations==[]
    from executive_health_ai.services.health_event_measurements import evaluate_window
    kwargs=dict(member_id=p.patient_id,metric='steps',threshold=8000,minimum_count=3,
        window_start=now-timedelta(days=1),window_end=now+timedelta(seconds=1),rule_id='synthetic-window')
    event=evaluate_window(s,**kwargs);same=evaluate_window(s,**kwargs)
    assert same.id==event.id and agent.wake_count==1
    assert event.payload_ref['risk_evaluation']['engine']=='deterministic'
    assert len(evaluations)==1
    assert s.scalar(select(func.count(AgentGoal.id)))==1 and len(human(s,p))==1


