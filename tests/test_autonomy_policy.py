def test_durable_tool_approval_resumes_its_own_step(db):
    from executive_health_ai.models import AgentPlan, AgentPlanStep, AgentApprovalRequest
    from executive_health_ai.agent.tools import AgentTool, AUTO
    s,p=db;supervisor=HealthOpsAgentSupervisor();_,g=change(s,p,'YELLOW',supervisor=supervisor)
    calls=[]
    supervisor.registry.register(AgentTool('test_operational_arrangement','合成权限验收',AUTO,'write',True,10,
        lambda *_: calls.append('executed') or {'prepared':True}))
    plan=s.get(AgentPlan,g.current_plan_id)
    step=s.scalar(select(AgentPlanStep).where(AgentPlanStep.plan_id==plan.id).order_by(AgentPlanStep.step_order))
    step.status,step.tool_name='PENDING','test_operational_arrangement'
    assert not supervisor._run_tool(s,g,plan,step,event_id=None)
    assert not calls and step.retry_count==0
    approval=s.scalar(select(AgentApprovalRequest).where(AgentApprovalRequest.plan_step_id==step.id))
    supervisor.decide_approval(s,approval.id,decision='APPROVED',actor='责任健管',actor_role='HEALTH_MANAGER')
    assert calls==['executed'] and step.status=='COMPLETED'


